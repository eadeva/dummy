def test_deep_merge_and_delete():
    base = {"A": 1, "B": {"x": 1, "y": 2}, "L": [1, 2]}
    assert sc.deep_merge(base, {"B": {"y": 3, "x": None}, "L": [9], "C": True}) == {
        "A": 1,
        "B": {"y": 3},
        "L": [9],
        "C": True,
    }
    assert base["B"] == {"x": 1, "y": 2}  # base untouched


def test_clang_tidy_checks_and_options():
    base = {
        "Checks": "-*,bugprone-*,cert-*,-readability-magic-numbers",
        "CheckOptions": [{"key": "a", "value": "1"}, {"key": "b", "value": "2"}],
        "FormatStyle": "file",
    }
    overlay = {
        "Checks": "-cert-*,readability-magic-numbers,google-*",
        "CheckOptions": {"b": "3", "a": None, "c": "4"},
    }
    merged = sc.merge_clang_tidy(base, overlay)
    assert (
        merged["Checks"] == "-*,bugprone-*,-cert-*,readability-magic-numbers,google-*"
    )
    assert merged["CheckOptions"] == [
        {"key": "b", "value": "3"},
        {"key": "c", "value": "4"},
    ]
    assert list(merged) == ["Checks", "CheckOptions", "FormatStyle"]


def test_pre_commit_merge():
    base = {
        "repos": [
            {
                "repo": "r1",
                "rev": "v1",
                "hooks": [{"id": "a"}, {"id": "b", "args": ["x"]}],
            },
            {"repo": "r2", "rev": "v1", "hooks": [{"id": "c"}]},
        ]
    }
    overlay = {
        "default_stages": ["pre-commit"],
        "repos": [
            {
                "repo": "r1",
                "rev": "v2",
                "hooks": [
                    {"id": "a", "disable": True},
                    {"id": "b", "args": ["y"]},
                    {"id": "d"},
                ],
            },
            {"repo": "r2", "disable": True},
            {
                "repo": "local",
                "hooks": [{"id": "mine", "entry": "x", "language": "system"}],
            },
        ],
    }
    merged = sc.merge_pre_commit(base, overlay)
    assert merged["default_stages"] == ["pre-commit"]
    assert [r["repo"] for r in merged["repos"]] == ["r1", "local"]
    assert merged["repos"][0] == {
        "repo": "r1",
        "rev": "v2",
        "hooks": [{"id": "b", "args": ["y"]}, {"id": "d"}],
    }


PROJECT = """
project: {name: cfg}
configs:
  pre-commit: {overlay: ptk/pc.yaml}
  ruff: {}
  clang-format: {overlay: ptk/cf.yaml}
  clang-tidy: {}
actions: {noop: {steps: [{x: "true"}]}}
"""


@pytest.fixture
def invoke(write):
    root = write(
        {
            ".main.ptk.yml": PROJECT,
            "ptk/pc.yaml": "repos:\n  - {repo: https://github.com/pre-commit/mirrors-clang-format, disable: true}\n",
            "ptk/cf.yaml": "ColumnLimit: 120\n",
        }
    )

    def _invoke(*args):
        return CliRunner().invoke(
            cli,
            ["--config", str(root / ".main.ptk.yml"), *args],
            catch_exceptions=False,
        )

    _invoke.root = root
    return _invoke


def test_sync_check_diff(invoke):
    root = invoke.root
    assert invoke("configs", "check").exit_code == 1
    preview = invoke("configs", "sync", "--diff")
    assert (
        "+++ b/.clang-format" in preview.output
        and not (root / ".clang-format").exists()
    )
    synced = invoke("configs", "sync")
    assert synced.exit_code == 0 and "new" in synced.output
    for name in (
        ".pre-commit-config.yaml",
        "ruff-base.toml",
        "ruff.toml",
        ".clang-format",
        ".clang-tidy",
    ):
        assert (root / name).is_file(), name
    assert not (root / ".clangd").exists()  # not configured -> not managed
    fmt = yaml.safe_load((root / ".clang-format").read_text())
    assert fmt["ColumnLimit"] == 120 and fmt["BasedOnStyle"] == "LLVM"
    assert (root / ".clang-format").read_text().startswith("# Generated by ptk")
    pc = yaml.safe_load((root / ".pre-commit-config.yaml").read_text())
    assert "https://github.com/pre-commit/mirrors-clang-format" not in [
        r["repo"] for r in pc["repos"]
    ]
    assert 'extend = "ruff-base.toml"' in (root / "ruff.toml").read_text()
    assert invoke("configs", "check").exit_code == 0
    # editing the overlay makes the effective file stale
    (root / "ptk/cf.yaml").write_text("ColumnLimit: 80\n")
    stale = invoke("configs", "check")
    assert stale.exit_code == 1 and "out of date" in stale.output
    assert (
        "-ColumnLimit: 120"
        in invoke("configs", "sync", "--diff", "clang-format").output
    )


def test_existing_ruff_toml_is_left_alone(invoke):
    (invoke.root / "ruff.toml").write_text("line-length = 100\n")
    result = invoke("configs", "sync", "ruff")
    assert 'add extend = "ruff-base.toml"' in result.output
    assert (invoke.root / "ruff.toml").read_text() == "line-length = 100\n"


def test_unknown_config_and_missing_overlay(invoke):
    assert "not managed" in invoke("configs", "sync", "clangd").output
    (invoke.root / "ptk/pc.yaml").unlink()
    assert "file not found: ptk/pc.yaml" in invoke("configs", "sync").output


def test_ruff_overlay_is_a_config_error(write, load):
    root = write(
        {".main.ptk.yml": "project: {name: x}\nconfigs: {ruff: {overlay: r.toml}}\n"}
    )
    with pytest.raises(ConfigError, match="ruff needs no overlay"):
        load(root)


@pytest.mark.skipif(shutil.which("ruff") is None, reason="ruff not installed")
def test_generated_ruff_config_works(invoke):
    invoke("configs", "sync")
    (invoke.root / "t.py").write_text("import sys, os\n")
    out = subprocess.run(
        ["ruff", "check", "--output-format", "concise", "t.py"],
        cwd=invoke.root,
        capture_output=True,
        text=True,
        check=False,
    ).stdout
    assert "I001" in out  # import sorting from the base is active


@pytest.mark.skipif(
    shutil.which("clang-format") is None, reason="clang-format not installed"
)
def test_generated_clang_format_works(invoke):
    invoke("configs", "sync")
    out = subprocess.run(
        ["clang-format", "--style=file", "--dump-config"],
        cwd=invoke.root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert "ColumnLimit:     120" in out
