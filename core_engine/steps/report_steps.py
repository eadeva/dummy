"""Test report collector step merges JUnit XMLs and exports HTML/PDF.
"""

import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path

from xc_ce_utils import logger
from xc_ce_utils.core_engine.domain.exceptions import ExecutionStepError
from xc_ce_utils.core_engine.domain.step_registry import StepRegistry
from xc_ce_utils.core_engine.steps.base import (
    BaseStepParams,
    ExecutionStep,
    StepExecutionStatus,
)


class TestReportCollectStepParams(BaseStepParams):
    pass
    model_config = {'extra': 'forbid'}


@StepRegistry.register('test_report_collect')
class TestReportCollectStep(ExecutionStep):
    params_model = TestReportCollectStepParams

    """Collects all JUnit XML reports and generates a merged report.

    Scans a reports directory for JUnit XML files generated by preceding
    test steps, merges them into a single consolidated report, and
    optionally exports it in additional formats (HTML, PDF).

    Config parameters:
        reports_dir (str):         Directory to scan for JUnit XML files.
                                   Default: step's reports_folder parent (action-level reports).
        output_formats (list):     List of output formats to generate.
                                   Supported: "junit", "html", "pdf".
                                   Default: ["junit", "html"]
        output_dir (str):          Directory for generated reports.
                                   Default: same as reports_dir.
        report_name (str):         Base filename for generated reports (no extension).
                                   Default: "test_report"
        html_template (str):       Path to custom Jinja2 HTML template (optional).
        glob_pattern (str):        Glob pattern for finding XML files.
                                   Default: "**/*.xml"
    """

    def execute(self) -> None:
        """Execute the report collection and export."""
        params = self.config.get('params', self.config)

        # Resolve reports directory (default: action-level reports folder)
        reports_dir = params.get('reports_dir', str(self.reports_folder.parent))
        output_dir = params.get('output_dir', reports_dir)
        report_name = params.get('report_name', 'test_report')
        output_formats = params.get('output_formats', ['junit', 'html'])
        if isinstance(output_formats, str):
            output_formats = [output_formats]
        html_template = params.get('html_template', None)
        glob_pattern = params.get('glob_pattern', '**/*.xml')
        use_unified_pipeline = bool(params.get('use_unified_pipeline', True))
        collect_log_findings = bool(params.get('collect_log_findings', True))
        log_findings_name = Path(
            str(params.get('log_findings_name', 'log-findings.canonical.json'))
        ).name
        max_log_findings = int(params.get('max_log_findings', 2000))
        emit_canonical_json = bool(params.get('emit_canonical_json', True))
        canonical_json_name = params.get('canonical_json_name', f'{report_name}.json')
        canonical_json_name = Path(str(canonical_json_name)).name

        logger.info(f'[{self.name}] Collecting test reports from: {reports_dir}')

        try:
            if not use_unified_pipeline:
                logger.warning(
                    f'[{self.name}] use_unified_pipeline=false is ignored; unified pipeline is always used'
                )

            normalized_formats = [fmt.lower() for fmt in output_formats]
            if 'pdf' in normalized_formats:
                logger.warning(
                    f'[{self.name}] Unified pipeline does not export PDF; skipping pdf output'
                )
                output_formats = [
                    fmt for fmt in output_formats if str(fmt).strip().lower() != 'pdf'
                ]

            from xc_ce_utils.core_engine.reporting import (
                build_default_reporting_pipeline,
            )

            if collect_log_findings:
                artifact_path = self._collect_log_findings_artifact(
                    reports_dir=Path(reports_dir),
                    artifact_name=log_findings_name,
                    max_findings=max_log_findings,
                )
                self.result_string.append(f'Log Findings: {artifact_path}')

            metadata = {
                'action': os.getenv('XC_CE_UTILS_ACTION', ''),
                'variant': os.getenv('XC_CE_UTILS_VARIANT_ALIAS', ''),
                'repo_root': str(getattr(self.context, 'repo_root', '')),
            }
            pipeline = build_default_reporting_pipeline()
            generated = pipeline.run(
                reports_dir=reports_dir,
                output_dir=output_dir,
                report_name=report_name,
                output_formats=output_formats,
                glob_pattern=params.get('unified_glob_pattern', '**/*'),
                metadata=metadata,
                reporting_config=getattr(self.context, 'reporting_config', None),
                emit_canonical_json=emit_canonical_json,
                canonical_json_name=canonical_json_name,
            )

            if not generated:
                logger.warning(
                    f'[{self.name}] Unified pipeline did not generate any report artifacts'
                )

            for _, path in generated.items():
                self.result_string.append(f'Report: {path}')
                logger.success(f'[{self.name}] Generated: {path}')

            self.execution_status = StepExecutionStatus.EXECUTE_SUCCESS

        except ImportError as e:
            self.abort(
                ExecutionStepError(f'[{self.name}] Missing dependency for report export: {e}')
            )
        except Exception as e:
            self.abort(ExecutionStepError(f'[{self.name}] Report collection failed: {e}'))

    def _collect_log_findings_artifact(
        self,
        reports_dir: Path,
        artifact_name: str,
        max_findings: int,
    ) -> Path:
        """Scan step logs and write canonical log-findings artifact."""
        max_findings = max(1, int(max_findings))
        execution_step_files = sorted(reports_dir.glob('**/execution-step.json'))

        warn_re = re.compile(r'\b(warning|warn)\b', re.IGNORECASE)
        error_re = re.compile(
            r'\b(error|fatal|exception|traceback)\b',
            re.IGNORECASE,
        )
        failure_re = re.compile(r'\b(failed|failure)\b', re.IGNORECASE)

        findings = []
        scanned_logs = 0
        missing_logs = 0

        for execution_file in execution_step_files:
            if len(findings) >= max_findings:
                break

            try:
                payload = json.loads(execution_file.read_text(encoding='utf-8'))
            except Exception:
                continue

            step = payload.get('step', {}) or {}
            step_name = str(step.get('name', 'unknown'))
            step_type = str(step.get('step_type', 'step'))
            log_path_raw = (payload.get('artifacts', {}) or {}).get('step_log', '')
            log_path = Path(str(log_path_raw)) if log_path_raw else None

            if log_path is None or not log_path.exists():
                missing_logs += 1
                continue

            scanned_logs += 1

            try:
                with log_path.open('r', encoding='utf-8', errors='replace') as handle:
                    for line_no, raw_line in enumerate(handle, start=1):
                        if len(findings) >= max_findings:
                            break

                        line = raw_line.strip()
                        if not line:
                            continue

                        sev, rule = self._classify_log_line(
                            line,
                            warn_re=warn_re,
                            error_re=error_re,
                            failure_re=failure_re,
                        )
                        if not sev:
                            continue

                        findings.append(
                            {
                                'tool': f'log:{step_type}',
                                'category': 'runtime-log',
                                'rule_id': rule,
                                'severity': sev,
                                'message': line[:1200],
                                'file': str(log_path),
                                'line': line_no,
                                'column': 0,
                                'status': 'open',
                                'source_file': str(execution_file),
                                'properties': {
                                    'step_name': step_name,
                                    'step_type': step_type,
                                },
                            }
                        )
            except Exception:
                continue

        artifact_dir = reports_dir / '_unified'
        artifact_dir.mkdir(parents=True, exist_ok=True)
        artifact_path = artifact_dir / artifact_name
        artifact_payload = {
            'report_kind': 'log-findings',
            'schema_version': '1.0.0',
            'generated_at': datetime.now(timezone.utc).isoformat(),
            'source': 'execution-step-logs',
            'scanned_logs': scanned_logs,
            'missing_logs': missing_logs,
            'total_findings': len(findings),
            'findings': findings,
        }
        artifact_path.write_text(
            json.dumps(artifact_payload, indent=2, ensure_ascii=False),
            encoding='utf-8',
        )

        logger.info(
            f'[{self.name}] Log findings artifact written: {artifact_path} '
            f'(findings={len(findings)}, scanned_logs={scanned_logs})'
        )
        return artifact_path

    def _classify_log_line(
        self,
        line: str,
        warn_re,
        error_re,
        failure_re,
    ):
        """Classify a raw log line into unified severity + rule id."""
        lowered = line.lower()

        # Avoid false positives from successful summaries.
        if '0 tests failed' in lowered or '0 test failed' in lowered:
            return None, None
        if '0 errors' in lowered and 'error' in lowered:
            return None, None
        if 'output-on-failure' in lowered:
            return None, None

        if 'traceback (most recent call last)' in lowered:
            return 'high', 'PY_TRACEBACK'
        if 'exception' in lowered:
            return 'high', 'PY_EXCEPTION'
        if error_re.search(line):
            return 'high', 'LOG_ERROR'
        if failure_re.search(line):
            return 'high', 'LOG_FAILURE'
        if warn_re.search(line):
            return 'medium', 'LOG_WARNING'

        return None, None
