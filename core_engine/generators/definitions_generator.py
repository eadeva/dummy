"""Generate native build-system definition files from variant configuration.

Replicates the preprocessor definitions and CMake variables that
``config/conan/xc-ce-conan-base/conanfile.py:generate_from_config()``
injects via ``conan_toolchain.cmake``, but without requiring Conan at all.

Supported outputs:
  * CMake   — ``xc_ce_definitions.cmake``
  * Make    — ``xc_ce_definitions.mk``
  * Bazel   — ``xc_ce_definitions.bzl``
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, List, Tuple

from xc_ce_utils import logger
from xc_ce_utils.core_engine.config.action_configuration import (
    ActionConfiguration,
)


class DefinitionsGenerator:
    """Collect variant definitions from *ActionConfiguration* and write them
    as native build-system files.

    The definitions mirror the Conan recipe output:
    * ``BO_<value>`` for every possible option value (0/1 active marker)
    * ``BO_<user>`` = 1  (first variant level / customer)
    * ``RB_MAJOR/MINOR/BUGFIX_VERSION_<PKG>``
    * ``RB_LONG/SHORT_COMMIT_HASH_<PKG>``, ``RB_GIT_DIRTY_<PKG>``
    * ``VARIANT_VERSION_<key>_<PKG>``
    * ``BO_<build_option>`` from build_options
    """

    def __init__(self, context: ActionConfiguration) -> None:
        self._ctx = context

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def collect(self) -> List[Tuple[str, Any]]:
        """Return an ordered list of ``(name, value)`` definition pairs."""
        ctx = self._ctx
        defs: List[Tuple[str, Any]] = []

        pkg = ctx.artifact.upper().replace('-', '_')

        # --- BO_<option_value> for ALL possible option values (0 / 1) ---
        active_values = set()
        for val in ctx.variant.get_variant_values().values():
            active_values.add(val.upper())

        # Walk the full variant matrix so we emit 0 for inactive options
        all_option_values: set[str] = set()
        vm_dict = ctx.variant_matrix.to_dict()
        for _vpath, vdata in vm_dict.get('variants', {}).items():
            for vv in vdata.get('variant_values', {}).values():
                all_option_values.add(vv.upper())

        for val in sorted(all_option_values):
            defs.append((f'BO_{val}', 1 if val in active_values else 0))

        # --- BO_<user> = 1 (first variant level = customer/user) ---
        user = next(iter(ctx.variant.get_variant_values().values()))
        user_key = f'BO_{user.upper()}'
        if user_key not in {d[0] for d in defs}:
            defs.append((user_key, 1))

        # --- Version splits ---
        version_parts = ctx.artifact_version.split('.')
        if len(version_parts) >= 3:
            bugfix_digits = ''.join(
                ch for ch in version_parts[2] if ch.isdigit()
            )
            defs.append((f'RB_MAJOR_VERSION_{pkg}', int(version_parts[0])))
            defs.append((f'RB_MINOR_VERSION_{pkg}', int(version_parts[1])))
            defs.append((f'RB_BUGFIX_VERSION_{pkg}', int(bugfix_digits or '0')))

        # --- Git info ---
        defs.append((f'RB_LONG_COMMIT_HASH_{pkg}', ctx.git_long_commit_hash))
        defs.append((f'RB_SHORT_COMMIT_HASH_{pkg}', ctx.git_short_commit_hash))
        defs.append((f'RB_GIT_DIRTY_{pkg}', ctx.git_is_dirty))

        # --- Variant version data ---
        variant_version = ctx.variant.get_version()
        if isinstance(variant_version, dict):
            for vk, vv in variant_version.items():
                defs.append((f'VARIANT_VERSION_{vk.upper()}_{pkg}', vv))

        # --- Build options (from global_defaults + per-variant overrides) ---
        build_options = ctx.variant.get_build_options()
        for bo_name, bo_value in build_options.items():
            defs.append((f'BO_{bo_name.upper()}', bo_value))

        return defs

    # ------------------------------------------------------------------
    # File writers
    # ------------------------------------------------------------------

    def write_cmake(self, output_dir: Path) -> Path:
        """Write ``xc_ce_definitions.cmake`` into *output_dir*."""
        output_dir.mkdir(parents=True, exist_ok=True)
        filepath = output_dir / 'xc_ce_definitions.cmake'
        defs = self.collect()

        lines = [
            '# Auto-generated by xc-ce-utils DefinitionsGenerator',
            '# Equivalent to conan_toolchain.cmake variable/preprocessor block',
            '',
            '# Always export compile_commands.json so IDEs / clang-tidy / clangd',
            '# can find an up-to-date compilation database under _build/<variant>/.',
            "# Safe to set alongside Conan's toolchain file (same value, idempotent).",
            'set(CMAKE_EXPORT_COMPILE_COMMANDS ON CACHE BOOL "Export compile_commands.json" FORCE)',
            '',
        ]

        # CMake variables
        for name, value in defs:
            cmake_val = self._cmake_value(value)
            force_suffix = ' FORCE' if self._cache_force_needed(name) else ''
            lines.append(
                f'set({name} {cmake_val} CACHE STRING "xc-ce-utils definition {name}"{force_suffix})'
            )

        lines.append('')

        # Preprocessor definitions (plain values — no inner quotes)
        #
        # Versioning / commit metadata stays as CMake cache variables only,
        # to avoid forcing a whole-project recompile when version.json or
        # commit hash changes. VersionInfoLib consumes these via generated
        # headers in the project CMake.
        for name, value in defs:
            if self._is_versioning_definition(name):
                continue
            plain_val = self._plain_value(value)
            lines.append(f'add_compile_definitions("{name}={plain_val}")')

        lines.append('')
        filepath.write_text('\n'.join(lines), encoding='utf-8')
        logger.debug(f'Generated {filepath}')
        return filepath

    def write_make(self, output_dir: Path) -> Path:
        """Write ``xc_ce_definitions.mk`` into *output_dir*."""
        output_dir.mkdir(parents=True, exist_ok=True)
        filepath = output_dir / 'xc_ce_definitions.mk'
        defs = self.collect()

        lines = [
            '# Auto-generated by xc-ce-utils DefinitionsGenerator',
            '',
        ]

        for name, value in defs:
            mk_val = self._plain_value(value)
            lines.append(f'{name} := {mk_val}')

        lines.append('')

        # CPPFLAGS convenience variable
        cpp_parts = [
            f'-D{name}={self._plain_value(value)}' for name, value in defs
        ]
        lines.append(f"XC_CE_DEFINITIONS_CPPFLAGS := {' '.join(cpp_parts)}")
        lines.append('')

        filepath.write_text('\n'.join(lines), encoding='utf-8')
        logger.debug(f'Generated {filepath}')
        return filepath

    def write_bazel(self, output_dir: Path) -> Path:
        """Write ``xc_ce_definitions.bzl`` into *output_dir*."""
        output_dir.mkdir(parents=True, exist_ok=True)
        filepath = output_dir / 'xc_ce_definitions.bzl'
        defs = self.collect()

        lines = [
            '"""Auto-generated by xc-ce-utils DefinitionsGenerator."""',
            '',
            'XC_CE_DEFINITIONS = {',
        ]

        for name, value in defs:
            bzl_val = self._bzl_value(value)
            lines.append(f'    "{name}": {bzl_val},')

        lines.append('}')
        lines.append('')

        # Convenience list for copts
        lines.append('XC_CE_COPTS = [')
        for name, value in defs:
            lines.append(f'    "-D{name}={self._plain_value(value)}",')
        lines.append(']')
        lines.append('')

        filepath.write_text('\n'.join(lines), encoding='utf-8')
        logger.debug(f'Generated {filepath}')
        return filepath

    # ------------------------------------------------------------------
    # Value formatting helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _cmake_value(value: Any) -> str:
        if isinstance(value, bool):
            return '1' if value else '0'
        if isinstance(value, str):
            return f'"{value}"'
        return str(value)

    @staticmethod
    def _plain_value(value: Any) -> str:
        if isinstance(value, bool):
            return '1' if value else '0'
        return str(value)

    @staticmethod
    def _bzl_value(value: Any) -> str:
        if isinstance(value, bool):
            return 'True' if value else 'False'
        if isinstance(value, str):
            return f'"{value}"'
        return str(value)

    @staticmethod
    def _cache_force_needed(name: str) -> bool:
        """Return True for cache keys that must override stale values.

        Dynamic versioning information can change between configure runs
        (e.g. commit hash, dirty flag, variant version values) while using
        the same build directory/cache.
        """
        return DefinitionsGenerator._is_versioning_definition(name)

    @staticmethod
    def _is_versioning_definition(name: str) -> bool:
        """Return True for version/commit related generated definitions."""
        return name.startswith('VARIANT_VERSION_') or (
            name.startswith('RB_')
            and (
                '_VERSION_' in name
                or '_COMMIT_HASH_' in name
                or '_GIT_DIRTY_' in name
            )
        )
