"""Create a minimal runnable project without requiring an existing configuration."""

import json
from dataclasses import dataclass
from pathlib import Path

from ...domain.errors import PtkError
from ..ports import ProjectScaffold

IGNORE = """# ptk generated workspace and local overrides
.ptk/
_builds/
_bin/
_logs/
_reports/
local.ptk.yml
"""


@dataclass(frozen=True)
class InitResult:
    files: dict[str, str]
    kept_gitignore: bool
    dry_run: bool


class InitProject:
    def __init__(self, scaffold: ProjectScaffold):
        self._scaffold = scaffold

    def execute(self, target: Path, name: str | None = None, *, dry_run=False):
        name = target.resolve().name if name is None else name.strip()
        if not name or any(ord(char) < 32 for char in name):
            raise PtkError(
                "project name must be non-empty and contain no control characters"
            )
        # JSON strings are valid YAML scalars and escape quotes/newlines safely.
        config = f"""# Generated by ptk setup init. Edit this file for your project.
schema_version: 1
project:
  name: {json.dumps(name, ensure_ascii=False)}
  default_action: hello
actions:
  hello:
    help: Run your first ptk action
    params:
      message: {{default: Hello from ptk, help: Message to display}}
    steps:
      - greet:
          uses: echo
          with:
            message: "${{params.message}}"
"""
        files = {"main.ptk.yml": config, ".gitignore": IGNORE}
        kept = self._scaffold.create(target, files, dry_run=dry_run)
        if kept:
            files.pop(".gitignore")
        return InitResult(files, kept, dry_run)
