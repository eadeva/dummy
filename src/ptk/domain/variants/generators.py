"""Portable variant exports. Pure functions returning filename -> UTF-8 text."""

import json

from ..errors import PtkError
from .model import feature_symbol


def values(variant):
    return {
        **{feature_symbol(k): v for k, v in variant.values.items()},
        **{
            f"VARIANT_COMPONENT_{c.upper()}": c in variant.components
            for c in variant.all_components
        },
        "VARIANT_NAME": variant.name,
    }


def scalar(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value)


def definition_items(variant):
    """Resolved preprocessor definitions as NAME=VALUE, or NAME without a value."""
    return [
        key if value is None else f"{key}={scalar(value)}"
        for key, value in variant.definitions.items()
    ]


def _flat_definitions(variant, tool):
    items = definition_items(variant)
    for item in items:
        if any(c.isspace() for c in item) or "\\" in item:
            raise PtkError(
                f"{tool} export does not support whitespace or backslashes in definitions: {item!r}"
            )
    return items


def header(variant):
    lines = ["/* Generated by ptk. */", "#pragma once"]
    for key, value in values(variant).items():
        literal = (
            json.dumps(value, ensure_ascii=True)
            if isinstance(value, str)
            else scalar(value)
        )
        lines.append(
            f"#define {key} {literal}" if value is not None else f"/* {key} inactive */"
        )
    for key, value in variant.definitions.items():
        lines.append(f"#ifndef {key}")
        lines.append(f"#define {key} {scalar(value)}".rstrip())
        lines.append("#endif")
    return {"variant.h": "\n".join(lines) + "\n"}


def _bracket(text):
    eq = ""
    while f"]{eq}]" in text:
        eq += "="
    return f"[{eq}[{text}]{eq}]"


def cmake(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        lines.append(f"set({key} {_bracket(scalar(value))})")
    for key, value in variant.definitions.items():
        lines.append(f"set({key} {_bracket(scalar(value))})")
    if variant.definitions:
        # Script mode (cmake -P) has no compile definitions.
        lines.append("if(NOT CMAKE_SCRIPT_MODE_FILE)")
        for definition in definition_items(variant):
            lines.append(f"  add_compile_definitions({_bracket(definition)})")
        lines.append("endif()")
    return {"variant.cmake": "\n".join(lines) + "\n"}


def bazel(variant):
    """Data exchange with the project-owned Bazel repository helper."""
    return {
        "variant.bazel.json": json.dumps(
            {
                "schema_version": 1,
                "values": values(variant),
                "definitions": definition_items(variant),
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    }


def _gn_string(value):
    if any(c in value for c in "\r\n\x00"):
        raise PtkError("GN export does not support newlines or NUL in strings")
    return (
        '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
    )


def gn(variant):
    lines = [
        "# Generated by ptk. Import this file from the project's GN configuration."
    ]
    for key, value in values(variant).items():
        if value is None:
            lines.append(f"# {key} inactive")
            continue
        if isinstance(value, str):
            literal = _gn_string(value)
        elif isinstance(value, bool):
            literal = "true" if value else "false"
        else:
            if not -(2**63) <= value < 2**63:
                raise PtkError("GN export requires signed 64-bit integer values")
            literal = str(value)
        lines.append(f"{key} = {literal}")
    defines = ", ".join(_gn_string(item) for item in definition_items(variant))
    lines.append(f"VARIANT_DEFINES = [{defines}]")
    return {"variant.gni": "\n".join(lines) + "\n"}


def make(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n\\") or text != text.strip():
            raise PtkError(
                "Make export does not support newlines, backslashes or surrounding whitespace in values"
            )
        text = text.replace("$", "$$").replace("#", r"\#")
        lines.append(f"{key} := {text}")
    items = [
        i.replace("$", "$$").replace("#", r"\#")
        for i in _flat_definitions(variant, "Make")
    ]
    lines.append("VARIANT_DEFINES := " + " ".join(items))
    lines.append("VARIANT_CPPFLAGS := " + " ".join("-D" + i for i in items))
    return {"variant.mk": "\n".join(lines) + "\n"}


def ninja(variant):
    lines = ["# Generated by ptk. Include this file from build.ninja."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n") or text != text.strip():
            raise PtkError(
                "Ninja export does not support newlines or surrounding whitespace in values"
            )
        lines.append(f"{key} = {text.replace('$', '$$')}")
    items = [i.replace("$", "$$") for i in _flat_definitions(variant, "Ninja")]
    lines.append("VARIANT_DEFINES = " + " ".join(items))
    lines.append("VARIANT_CPPFLAGS = " + " ".join("-D" + i for i in items))
    return {"variant.ninja": "\n".join(lines) + "\n"}


def yocto(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n") or "${" in text:
            raise PtkError(
                "Yocto export does not support newlines or variable expansions in values"
            )
        text = text.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key} = "{text}"')
    items = _flat_definitions(variant, "Yocto")
    if any("${" in i for i in items):
        raise PtkError(
            "Yocto export does not support variable expansions in definitions"
        )
    items = [i.replace('"', '\\"') for i in items]
    lines.append('VARIANT_DEFINES = "' + " ".join(items) + '"')
    lines.append('VARIANT_CPPFLAGS = "' + " ".join("-D" + i for i in items) + '"')
    return {"variant.inc": "\n".join(lines) + "\n"}


def robot(variant):
    lines = ["*** Variables ***"]
    for key, value in values(variant).items():
        text = (
            scalar(value)
            .replace("\\", "\\\\")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        for prefix in ("$", "@", "&", "%"):
            text = text.replace(prefix + "{", "\\" + prefix + "{")
        text = text.replace("  ", " \\ ")
        lines.append("${" + key + "}\t" + (text or "${EMPTY}"))
    return {"variant.robot": "\n".join(lines) + "\n"}


def sphinx(variant):
    body = json.dumps(values(variant), indent=2, ensure_ascii=False)
    return {
        "variant.rst": "Variant "
        + variant.name
        + "\n"
        + "=" * (8 + len(variant.name))
        + "\n\n.. code-block:: json\n\n"
        + "\n".join("   " + line for line in body.splitlines())
        + "\n"
    }


