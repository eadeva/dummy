"""Portable variant exports. Pure functions returning filename -> UTF-8 text."""

import json

from ..errors import PtkError
from .model import feature_symbol


def values(variant):
    return {
        **{feature_symbol(k): v for k, v in variant.values.items()},
        **{
            f"VARIANT_COMPONENT_{c.upper()}": c in variant.components
            for c in variant.all_components
        },
        "VARIANT_NAME": variant.name,
    }


def scalar(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value)


def header(variant):
    lines = ["/* Generated by ptk. */", "#pragma once"]
    for key, value in values(variant).items():
        literal = (
            json.dumps(value, ensure_ascii=True)
            if isinstance(value, str)
            else scalar(value)
        )
        lines.append(
            f"#define {key} {literal}" if value is not None else f"/* {key} inactive */"
        )
    return {"variant.h": "\n".join(lines) + "\n"}


def cmake(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        eq = ""
        while f"]{eq}]" in text:
            eq += "="
        lines.append(f"set({key} [{eq}[{text}]{eq}])")
    return {"variant.cmake": "\n".join(lines) + "\n"}


def bazel(variant):
    """Data exchange with the project-owned Bazel repository helper."""
    return {
        "variant.bazel.json": json.dumps(
            {"schema_version": 1, "values": values(variant)},
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    }


def gn(variant):
    lines = [
        "# Generated by ptk. Import this file from the project's GN configuration."
    ]
    for key, value in values(variant).items():
        if value is None:
            lines.append(f"# {key} inactive")
            continue
        if isinstance(value, str):
            if any(c in value for c in "\r\n\x00"):
                raise PtkError("GN export does not support newlines or NUL in strings")
            literal = (
                '"'
                + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
                + '"'
            )
        elif isinstance(value, bool):
            literal = "true" if value else "false"
        else:
            if not -(2**63) <= value < 2**63:
                raise PtkError("GN export requires signed 64-bit integer values")
            literal = str(value)
        lines.append(f"{key} = {literal}")
    return {"variant.gni": "\n".join(lines) + "\n"}


def make(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n\\") or text != text.strip():
            raise PtkError(
                "Make export does not support newlines, backslashes or surrounding whitespace in values"
            )
        text = text.replace("$", "$$").replace("#", r"\#")
        lines.append(f"{key} := {text}")
    return {"variant.mk": "\n".join(lines) + "\n"}


def yocto(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n") or "${" in text:
            raise PtkError(
                "Yocto export does not support newlines or variable expansions in values"
            )
        text = text.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key} = "{text}"')
    return {"variant.inc": "\n".join(lines) + "\n"}


def robot(variant):
    lines = ["*** Variables ***"]
    for key, value in values(variant).items():
        text = (
            scalar(value)
            .replace("\\", "\\\\")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        for prefix in ("$", "@", "&", "%"):
            text = text.replace(prefix + "{", "\\" + prefix + "{")
        text = text.replace("  ", " \\ ")
        lines.append("${" + key + "}\t" + (text or "${EMPTY}"))
    return {"variant.robot": "\n".join(lines) + "\n"}


def sphinx(variant):
    body = json.dumps(values(variant), indent=2, ensure_ascii=False)
    return {
        "variant.rst": "Variant "
        + variant.name
        + "\n"
        + "=" * (8 + len(variant.name))
        + "\n\n.. code-block:: json\n\n"
        + "\n".join("   " + line for line in body.splitlines())
        + "\n"
    }


GENERATORS = {
    "header": header,
    "cmake": cmake,
    "bazel": bazel,
    "gn": gn,
    "make": make,
    "yocto": yocto,
    "robot": robot,
    "sphinx": sphinx,
}
