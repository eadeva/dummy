"""Portable variant exports. Pure functions returning filename -> UTF-8 text."""

import json

from ..errors import PtkError


def values(variant):
    return {
        **{f"VH_{k}": v for k, v in variant.values.items()},
        **{
            f"VH_COMPONENT_{c.upper()}": c in variant.components
            for c in variant.all_components
        },
        "VH_VARIANT": variant.name,
    }


def scalar(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value)


def header(variant):
    lines = ["/* Generated by ptk. */", "#pragma once"]
    for key, value in values(variant).items():
        literal = (
            json.dumps(value, ensure_ascii=True)
            if isinstance(value, str)
            else scalar(value)
        )
        lines.append(
            f"#define {key} {literal}" if value is not None else f"/* {key} inactive */"
        )
    return {"variant.h": "\n".join(lines) + "\n"}


def cmake(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        eq = ""
        while f"]{eq}]" in text:
            eq += "="
        lines.append(f"set({key} [{eq}[{text}]{eq}])")
    return {"variant.cmake": "\n".join(lines) + "\n"}


def bazel(variant):
    return {
        "variant.bzl": "# Generated by ptk.\nVARIANT = " + repr(values(variant)) + "\n"
    }


def make(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n\\") or text != text.strip():
            raise PtkError(
                "Make export does not support newlines, backslashes or surrounding whitespace in values"
            )
        text = text.replace("$", "$$").replace("#", r"\#")
        lines.append(f"{key} := {text}")
    return {"variant.mk": "\n".join(lines) + "\n"}


def yocto(variant):
    lines = ["# Generated by ptk."]
    for key, value in values(variant).items():
        text = scalar(value)
        if any(c in text for c in "\r\n") or "${" in text:
            raise PtkError(
                "Yocto export does not support newlines or variable expansions in values"
            )
        text = text.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key} = "{text}"')
    return {"variant.inc": "\n".join(lines) + "\n"}


def robot(variant):
    lines = ["*** Variables ***"]
    for key, value in values(variant).items():
        text = (
            scalar(value)
            .replace("\\", "\\\\")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        for prefix in ("$", "@", "&", "%"):
            text = text.replace(prefix + "{", "\\" + prefix + "{")
        text = text.replace("  ", " \\ ")
        lines.append("${" + key + "}\t" + (text or "${EMPTY}"))
    return {"variant.robot": "\n".join(lines) + "\n"}


def sphinx(variant):
    body = json.dumps(values(variant), indent=2, ensure_ascii=False)
    return {
        "variant.rst": "Variant "
        + variant.name
        + "\n"
        + "=" * (8 + len(variant.name))
        + "\n\n.. code-block:: json\n\n"
        + "\n".join("   " + line for line in body.splitlines())
        + "\n"
    }


GENERATORS = {
    "header": header,
    "cmake": cmake,
    "bazel": bazel,
    "make": make,
    "yocto": yocto,
    "robot": robot,
    "sphinx": sphinx,
}
