"""Git-aware pre-commit installation, including gitfiles and linked worktrees.

The engine lives under Git's common directory, so shared hooks never depend on
a disposable uv tool cache or another worktree's project virtual environment.
"""

from __future__ import annotations

import os
import shlex
import sys
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from pathlib import Path

import yaml

from ..application.ports import HookStatus, ProcessOutcome, ProcessRunner
from ..domain.errors import PtkError
from ..domain.execution.model import CommandSpec
from .locking import file_lock
from .python_env import venv_python

ENGINE = "pre-commit>=4,<5"
GENERATED = "# File generated by pre-commit: https://pre-commit.com"
# Match the framework's current and historical generated-script identifiers
# before allowing its migration behavior to rename an existing hook.
SCRIPT_IDS = (
    "138fd403232d2ddd5efb44317e38bf03",
    "4d9958c90bc262f47553e2c073f14cfe",
    "d8ee923c46731b42cd95cc869add4062",
    "49fd668cb42069aa1b6048464be5d395",
    "79f09a650522a87b0da915d0d983b2de",
    "e358c9dae00eac5d06b38dfdb1e33a8c",
)
HOOK_TYPES = frozenset(
    {
        "pre-commit",
        "pre-merge-commit",
        "pre-push",
        "prepare-commit-msg",
        "commit-msg",
        "post-commit",
        "post-checkout",
        "post-merge",
        "post-rewrite",
        "pre-rebase",
    }
)
# A PTK invocation inside a Git hook must not redirect VMR member Git commands
# back to the caller's repository. Keep ordinary Git configuration/auth settings.
GIT_PATH_VARIABLES = frozenset(
    {
        "GIT_DIR",
        "GIT_COMMON_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_PREFIX",
        "GIT_IMPLICIT_WORK_TREE",
    }
)


@dataclass(frozen=True)
class HookTarget:
    root: Path
    common: Path
    config: str
    types: tuple[str, ...]

    def path(self, kind: str) -> Path:
        return self.common / "hooks" / kind


class GitHooks:
    def __init__(self, runner: ProcessRunner, environ: Mapping[str, str], *, uv: str):
        self._runner = runner
        self._env = {k: v for k, v in environ.items() if k not in GIT_PATH_VARIABLES}
        self._uv = uv

    def _call(
        self,
        root: Path,
        argv: list[str],
        *,
        timeout: float | None = 30,
        out: Callable[[str], None] | None = None,
    ) -> tuple[ProcessOutcome, str]:
        lines = []

        def output(line):
            lines.append(line)
            if out:
                out(line)

        result = self._runner.run(
            CommandSpec(argv=argv, cwd=str(root), env=self._env, timeout=timeout),
            output,
        )
        return result, "\n".join(lines).strip()

    def _checked(self, root: Path, argv: list[str], **kwargs) -> str:
        result, text = self._call(root, argv, **kwargs)
        if result.exit_code:
            detail = result.error or ("timed out" if result.timed_out else text)
            raise PtkError(
                f"pre-commit setup failed in {root}: {detail or 'command failed'}"
            )
        return text

    def _target(
        self, root: Path, config: Path, *, check_hooks_path: bool = True
    ) -> HookTarget:
        if not config.is_file():
            raise PtkError(
                f"pre-commit configuration missing: {config}; ask a maintainer to run "
                "'ptk setup configs sync pre-commit' and commit the result"
            )
        try:
            data = yaml.safe_load(config.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, yaml.YAMLError) as exc:
            raise PtkError(
                f"cannot read pre-commit configuration {config}: {exc}"
            ) from None
        kinds = (
            data.get("default_install_hook_types", ["pre-commit"])
            if isinstance(data, dict)
            else None
        )
        if (
            not isinstance(kinds, list)
            or not kinds
            or any(not isinstance(k, str) or k not in HOOK_TYPES for k in kinds)
            or not isinstance(data.get("repos"), list)
        ):
            raise PtkError(
                f"invalid pre-commit configuration: {config} (repos and supported default_install_hook_types required)"
            )
        paths = self._checked(
            root,
            [
                "git",
                "rev-parse",
                "--path-format=absolute",
                "--show-toplevel",
                "--git-common-dir",
            ],
        ).splitlines()
        if len(paths) != 2 or not Path(paths[0]).samefile(root):
            raise PtkError(f"pre-commit requires a Git repository rooted at {root}")
        result, custom = self._call(root, ["git", "config", "--get", "core.hooksPath"])
        if result.exit_code == 0 and check_hooks_path:
            raise PtkError(
                f"pre-commit hook conflict in {root}: core.hooksPath is set to {custom!r}; "
                "ask a maintainer to reconcile the existing hook configuration"
            )
        if result.exit_code not in (0, 1):
            raise PtkError(
                f"cannot inspect Git hook configuration in {root}: {result.error or custom}"
            )
        # Relative config paths also work when hooks are shared by linked worktrees.
        return HookTarget(
            root,
            Path(paths[1]).resolve(),
            os.path.relpath(config, root),
            tuple(dict.fromkeys(kinds)),
        )

    def _python(self, target: HookTarget, kind: str) -> str | None:
        hook = target.path(kind)
        if hook.is_symlink() or not hook.is_file() or not os.access(hook, os.X_OK):
            return None
        text = hook.read_text(encoding="utf-8", errors="replace")
        if (
            GENERATED not in text
            or not any(s in text for s in SCRIPT_IDS)
            or 'exec "$INSTALL_PYTHON" -mpre_commit' not in text
        ):
            return None
        lines = text.splitlines()
        try:
            python = next(line for line in lines if line.startswith("INSTALL_PYTHON="))
            [python] = shlex.split(python.split("=", 1)[1])
            args = next(
                line
                for line in lines
                if line.startswith("ARGS=(") and line.endswith(")")
            )
            args = shlex.split(args[len("ARGS=(") : -1])
        except (StopIteration, ValueError):
            return None
        expected = ["hook-impl", f"--config={target.config}", f"--hook-type={kind}"]
        if (
            args != expected
            or not Path(python).is_file()
            or not os.access(python, os.X_OK)
        ):
            return None
        return python

    def _usable_python(self, root: Path, python: str) -> bool:
        result, text = self._call(root, [python, "-I", "-m", "pre_commit", "--version"])
        return result.exit_code == 0 and text.startswith("pre-commit ")

    def _status(self, target: HookTarget) -> HookStatus:
        checked = {}
        missing = []
        for kind in target.types:
            python = self._python(target, kind)
            if python and python not in checked:
                checked[python] = self._usable_python(target.root, python)
            if not python or not checked[python]:
                missing.append(kind)
        if missing:
            return HookStatus(False, "missing or unusable: " + ", ".join(missing))
        return HookStatus(
            True, f"installed ({', '.join(target.types)}): {target.common / 'hooks'}"
        )

    def status(self, root: Path, config: Path) -> HookStatus:
        try:
            return self._status(self._target(root, config))
        except OSError as exc:
            raise PtkError(
                f"cannot inspect pre-commit hooks in {root}: {exc}"
            ) from None

    def _runtime(self, target: HookTarget, out: Callable[[str], None]) -> str:
        env = target.common / "ptk" / "pre-commit"
        python = str(venv_python(env))
        if Path(python).is_file() and self._usable_python(target.root, python):
            return python
        if not Path(python).is_file():
            self._checked(
                target.root,
                [self._uv, "venv", "--clear", "--python", sys.executable, str(env)],
                timeout=120,
                out=out,
            )
        self._checked(
            target.root,
            [self._uv, "pip", "install", "--reinstall", "--python", python, ENGINE],
            timeout=300,
            out=out,
        )
        if not self._usable_python(target.root, python):
            raise PtkError(f"pre-commit runtime is unusable: {python}")
        return python

    def ensure(self, root: Path, config: Path, out: Callable[[str], None]) -> None:
        try:
            target = self._target(root, config)
            if self._status(target).installed:
                return
            # Serialize independent PTK processes and worktrees sharing Git hooks.
            with file_lock(target.common / "ptk" / "pre-commit.lock", timeout=600):
                if self._status(target).installed:
                    return
                for kind in target.types:
                    hook = target.path(kind)
                    backup = hook.with_name(kind + ".legacy")
                    if hook.is_symlink() or (hook.exists() and not hook.is_file()):
                        raise PtkError(
                            f"pre-commit hook conflict: {hook}; existing hook left unchanged"
                        )
                    if (
                        hook.is_file()
                        and not any(
                            s in hook.read_text(encoding="utf-8", errors="replace")
                            for s in SCRIPT_IDS
                        )
                        and (backup.exists() or backup.is_symlink())
                    ):
                        raise PtkError(
                            f"pre-commit hook conflict: both {hook} and its .legacy backup exist; left unchanged"
                        )
                out(f"ptk: installing pre-commit hooks in {root}")
                python = self._runtime(target, out)
                prefix = [python, "-I", "-m", "pre_commit"]
                self._checked(
                    root, [*prefix, "validate-config", target.config], out=out
                )
                self._checked(
                    root,
                    [
                        *prefix,
                        "install",
                        "--config",
                        target.config,
                        *[
                            arg
                            for kind in target.types
                            for arg in ("--hook-type", kind)
                        ],
                    ],
                    out=out,
                )
                status = self._status(target)
                if not status.installed:
                    raise PtkError(
                        f"pre-commit installation verification failed in {root}: {status.detail}"
                    )
        except OSError as exc:
            raise PtkError(
                f"cannot install pre-commit hooks in {root}: {exc}"
            ) from None

    def run(
        self, root: Path, config: Path, args: list[str], out: Callable[[str], None]
    ) -> ProcessOutcome:
        """Run checks or validate configuration without installing Git hook scripts."""
        try:
            target = self._target(root, config, check_hooks_path=False)
            with file_lock(target.common / "ptk" / "pre-commit.lock", timeout=600):
                python = self._runtime(target, out)
            if args[0] == "validate-config":
                command = ["validate-config", target.config]
            else:
                command = [args[0], "--config", target.config, *args[1:]]
            result, _ = self._call(
                root,
                [python, "-I", "-m", "pre_commit", *command],
                timeout=None,
                out=out,
            )
            return result
        except OSError as exc:
            raise PtkError(f"cannot run pre-commit in {root}: {exc}") from None

    def uninstall(self, root: Path, config: Path, out: Callable[[str], None]) -> None:
        try:
            target = self._target(root, config)
            with file_lock(target.common / "ptk" / "pre-commit.lock", timeout=600):
                for kind in target.types:
                    hook = target.path(kind)
                    backup = hook.with_name(kind + ".legacy")
                    if (
                        hook.is_symlink()
                        or backup.is_symlink()
                        or any(p.exists() and not p.is_file() for p in (hook, backup))
                    ):
                        raise PtkError(
                            f"pre-commit hook conflict: {hook}; left unchanged"
                        )
                python = self._runtime(target, out)
                self._checked(
                    root,
                    [
                        python,
                        "-I",
                        "-m",
                        "pre_commit",
                        "uninstall",
                        "--config",
                        target.config,
                        *[
                            arg
                            for kind in target.types
                            for arg in ("--hook-type", kind)
                        ],
                    ],
                    out=out,
                )
        except OSError as exc:
            raise PtkError(
                f"cannot uninstall pre-commit hooks in {root}: {exc}"
            ) from None
