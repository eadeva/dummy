const { chromium } = require(process.env.PTK_TEST_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PTK_TEST_CHROMIUM, args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(require('node:url').pathToFileURL(process.argv[2]).href);
    const diagnostics = page.locator('#diagnostics');
    const tests = page.locator('#tests');
    assert.equal(await tests.locator('.test-case:visible').count(), 4);
    const cards = await page.locator('.cards').allTextContents();
    await tests.getByRole('searchbox').fill('parser');
    assert.equal(await tests.locator('.test-case:visible').count(), 2);
    await tests.getByLabel('Test result', { exact: true }).selectOption('failed');
    assert.equal(await tests.locator('.test-case:visible').count(), 1);
    await tests.getByRole('searchbox').fill('no-match');
    assert.equal(await tests.locator('.test-case:visible').count(), 0);
    await tests.getByRole('button', { name: 'Reset filters', exact: true }).click();
    assert.equal(await tests.locator('.test-case:visible').count(), 4);
    assert.deepEqual(await page.locator('.cards').allTextContents(), cards);
    await diagnostics.getByLabel('Source', { exact: true }).selectOption('log');
    assert.equal(await diagnostics.locator('.diagnostic:visible').count(), 2);
    assert.match(await diagnostics.locator('[data-filter-count]').textContent(), /3 log occurrences/);
    await diagnostics.getByRole('button', { name: 'Show justified log findings', exact: true }).click();
    const justified = diagnostics.locator('.diagnostic:visible');
    await justified.locator('summary').click();
    assert.match(await justified.innerText(), /Upgrade pending/);
    await diagnostics.getByRole('button', { name: 'Show active log errors', exact: true }).click();
    const error = diagnostics.locator('.diagnostic:visible');
    await error.locator('summary').click();
    assert.match(await error.innerText(), /AssertionError: <expected>/);
    assert.equal(await error.getByRole('link').getAttribute('href'), 'pytest.log');
    await diagnostics.getByLabel('Step', { exact: true }).selectOption('compile');
    assert.equal(await diagnostics.locator('.diagnostic:visible').count(), 0);
    await diagnostics.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await diagnostics.getByRole('searchbox').fill('SDK');
    assert.equal(await diagnostics.locator('.diagnostic:visible').count(), 1);
    await diagnostics.getByLabel('Disposition', { exact: true }).selectOption('');
    assert.equal(await diagnostics.locator('.diagnostic:visible').count(), 2);
    // A failure permalink reveals evidence even if the current filters hide it.
    await page.locator('#failures a').first().click();
    const selected = page.locator(await page.evaluate(() => location.hash));
    assert.equal(await selected.evaluate(node => node.open), true);
    assert.equal(await selected.isVisible(), true);
    await page.getByRole('navigation').getByRole('link', { name: 'Overview', exact: true }).click();
    await page.screenshot({ path: '/tmp/ptk-report-overview.png', fullPage: false });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('Report navigation, combined diagnostics, source separation, test filters, evidence links, permalink reveal and mobile layout passed');
  } finally { await browser.close(); }
})();
